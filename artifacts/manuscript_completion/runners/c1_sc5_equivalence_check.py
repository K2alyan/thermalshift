#!/usr/bin/env python3
"""
c1_sc5_equivalence_check.py — Compare parallel sc5 output against sequential reference

Compares the sc5 result produced by the parallel launcher against the sc5
extracted from the interrupted sequential c1 production run. Both should have
been generated by the identical frozen c1_gate_f_run.py with identical seeds.

Scientific equivalence requires exact equality on all numerical and categorical
fields. Only operational metadata fields (elapsed_s, timestamps) are excluded.

Usage:
  python3 c1_sc5_equivalence_check.py \\
    --sequential artifacts/manuscript_completion/SEQUENTIAL_SC5_REFERENCE.json \\
    --parallel   artifacts/manuscript_completion/results/gate_f_sc5-5_all.json

Exit codes: 0 = PASS, 1 = FAIL.
"""

import sys, json, math, argparse
from pathlib import Path

# Fields in scenario_result that are operational (permitted to differ)
_OPERATIONAL_FIELDS = {"elapsed_s"}

# Fields in lambda_rows that are operational
_OPERATIONAL_ROW_FIELDS = set()   # none — all must match


def _deep_eq(a, b, path: str, mismatches: list, tol: float = 0.0):
    """
    Recursively compare a and b. Exact equality for ints/strings/bools/None.
    Floats use tolerance tol (default 0.0 → exact bitwise).
    Appends to mismatches list on any difference.
    """
    if type(a) != type(b):
        # Allow int/float interop
        if isinstance(a, (int, float)) and isinstance(b, (int, float)):
            fa, fb = float(a), float(b)
            if math.isnan(fa) and math.isnan(fb):
                return
            if abs(fa - fb) > tol:
                mismatches.append(f"{path}: {a!r} != {b!r}  (diff={abs(fa-fb):.2e})")
            return
        mismatches.append(f"{path}: type mismatch {type(a).__name__} vs {type(b).__name__}")
        return

    if isinstance(a, dict):
        keys_a, keys_b = set(a.keys()), set(b.keys())
        for k in keys_a - keys_b:
            mismatches.append(f"{path}.{k}: key present in A but missing in B")
        for k in keys_b - keys_a:
            mismatches.append(f"{path}.{k}: key present in B but missing in A")
        for k in keys_a & keys_b:
            _deep_eq(a[k], b[k], f"{path}.{k}", mismatches, tol)

    elif isinstance(a, list):
        if len(a) != len(b):
            mismatches.append(f"{path}: list length {len(a)} vs {len(b)}")
            return
        for i, (ai, bi) in enumerate(zip(a, b)):
            _deep_eq(ai, bi, f"{path}[{i}]", mismatches, tol)

    elif isinstance(a, float):
        if math.isnan(a) and math.isnan(b):
            return
        if abs(a - b) > tol:
            mismatches.append(f"{path}: {a!r} != {b!r}  (diff={abs(a-b):.2e})")

    else:  # int, str, bool, None
        if a != b:
            mismatches.append(f"{path}: {a!r} != {b!r}")


def _strip_operational(sc: dict) -> dict:
    """Return a copy of scenario_result dict with operational fields removed."""
    return {k: v for k, v in sc.items() if k not in _OPERATIONAL_FIELDS}


def compare_scenario(seq_sc: dict, par_sc: dict) -> list[str]:
    """
    Compare two scenario result dicts. Returns list of mismatch descriptions.
    Empty list = PASS.
    """
    mismatches = []

    # Strip operational fields before comparison
    a = _strip_operational(seq_sc)
    b = _strip_operational(par_sc)

    _deep_eq(a, b, "scenario", mismatches, tol=0.0)
    return mismatches


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sequential", type=Path, required=True,
                        help="Sequential sc5 reference JSON (scenario_result dict)")
    parser.add_argument("--parallel",   type=Path, required=True,
                        help="Parallel sc5 output JSON (full per-scenario worker JSON)")
    args = parser.parse_args()

    if not args.sequential.exists():
        sys.exit(f"Sequential reference not found: {args.sequential}")
    if not args.parallel.exists():
        sys.exit(f"Parallel output not found: {args.parallel}")

    # Load sequential reference (pure scenario_result dict)
    with open(args.sequential) as f:
        seq_sc = json.load(f)
    assert seq_sc.get("scenario_idx") == 5, "Sequential reference must be sc5"

    # Load parallel output (per-scenario worker JSON — extract scenario_results[0])
    with open(args.parallel) as f:
        par_full = json.load(f)
    par_results = par_full.get("scenario_results", [])
    if len(par_results) != 1:
        sys.exit(f"Parallel output has {len(par_results)} scenario_results — expected 1 (N_DEV=1)")
    par_sc = par_results[0]
    assert par_sc.get("scenario_idx") == 5, "Parallel output must be sc5"

    print(f"Sequential sc5: {args.sequential.name}")
    print(f"  scen_seed={seq_sc['scen_seed']}  wl_seed={seq_sc['wl_seed']}")
    print(f"Parallel sc5:   {args.parallel.name}")
    print(f"  scen_seed={par_sc['scen_seed']}  wl_seed={par_sc['wl_seed']}")
    print()

    # Seed check first — if seeds differ, comparison will trivially fail
    if seq_sc["scen_seed"] != par_sc["scen_seed"] or seq_sc["wl_seed"] != par_sc["wl_seed"]:
        print("[FAIL] Seed mismatch — comparing different scenarios")
        print(f"  seq: scen_seed={seq_sc['scen_seed']}  wl_seed={seq_sc['wl_seed']}")
        print(f"  par: scen_seed={par_sc['scen_seed']}  wl_seed={par_sc['wl_seed']}")
        sys.exit(1)

    mismatches = compare_scenario(seq_sc, par_sc)

    if mismatches:
        print(f"[FAIL] {len(mismatches)} mismatch(es):")
        for m in mismatches:
            print(f"  {m}")
        sys.exit(1)

    print("[PASS] sc5 equivalence: all scientific fields match exactly.")
    print(f"  Ratios compared: {list(seq_sc['ratios'].keys())}")
    print(f"  Policies per ratio: {list(list(seq_sc['ratios'].values())[0].keys())}")

    # Count fields compared
    import json as _json
    seq_str = _json.dumps(_strip_operational(seq_sc))
    print(f"  Approximate field-value pairs compared: {seq_str.count(':')}")


if __name__ == "__main__":
    main()
